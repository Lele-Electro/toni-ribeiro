// Builds the site and assembles dist/afrihost: the folder whose CONTENTS are uploaded by
// FTP to public_html on Afrihost (static hosting, no Node server).
//
//   npm run build:afrihost
//
// The prerendered pages are served as they are; every other route (password reset, unknown
// URLs) falls back to the client-rendered shell through .htaccess. The lift club (and its
// /events and /reviews views) is also rendered in the browser, but each address gets its own
// copy of the shell carrying its title, description and share image, because link previews
// (WhatsApp, Facebook) never run scripts. The home page is switched off: / redirects to the
// lift club (see app.routes.ts).
import { execSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
// Plain TypeScript data modules, loaded directly (Node strips the types).
import { SITE_NAME } from '../src/app/core/site.config.ts';
import {
  DEFAULT_DESCRIPTION,
  LIFT_CLUB_EVENTS_PAGE,
  LIFT_CLUB_PAGE,
  LIFT_CLUB_REVIEWS_PAGE,
  fullTitle,
  pageTags,
} from '../src/app/core/seo/page-tags.ts';
import { environment } from '../src/environments/environment.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const browser = join(root, 'dist/toni-ribeiro/browser');
const out = join(root, 'dist/afrihost');

execSync('npx ng build', { cwd: root, stdio: 'inherit' });

rmSync(out, { recursive: true, force: true });
cpSync(browser, out, { recursive: true });

const escapeHtml = (value) =>
  String(value).replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');

/** Replaces the page's title, search and social tags, as server rendering would. */
function withHead(html, { title, ...page }) {
  const tags = pageTags({ siteName: SITE_NAME, siteUrl: environment.siteUrl, title, ...page });
  const keys = new Set(tags.map((tag) => tag.property ?? tag.name));
  const lines = tags.map((tag) =>
    'property' in tag
      ? `<meta property="${tag.property}" content="${escapeHtml(tag.content)}">`
      : `<meta name="${tag.name}" content="${escapeHtml(tag.content)}">`,
  );
  if (page.url) lines.push(`<link rel="canonical" href="${escapeHtml(page.url)}">`);
  if (!html.includes('</head>')) throw new Error('The app shell has no </head>.');
  return html
    .replace(/[ \t]*<meta\b[^>]*\b(?:name|property)="([^"]+)"[^>]*>\r?\n?/g, (tag, key) => (keys.has(key) ? '' : tag))
    .replace(/[ \t]*<link rel="canonical"[^>]*>\r?\n?/, '')
    .replace(/<title>[^<]*<\/title>/, `<title>${escapeHtml(title)}</title>`)
    .replace('</head>', `${lines.map((line) => `    ${line}\n`).join('')}  </head>`);
}

const shell = 'index.csr.html';
if (!existsSync(join(out, shell))) throw new Error(`${shell} is missing from the build.`);
// The shell is served at many addresses, so it names no canonical URL.
const shellHtml = withHead(readFileSync(join(out, shell), 'utf8'), {
  title: SITE_NAME,
  description: DEFAULT_DESCRIPTION,
});
writeFileSync(join(out, shell), shellHtml);
// Without a prerendered home page, the shell is the home page.
if (!existsSync(join(out, 'index.html'))) cpSync(join(out, shell), join(out, 'index.html'));

// /lift-club -> lift-club/index.html, and the same for /events and /reviews (see the
// .htaccess rules below).
for (const page of [LIFT_CLUB_PAGE, LIFT_CLUB_EVENTS_PAGE, LIFT_CLUB_REVIEWS_PAGE]) {
  const folder = join(out, page.path);
  mkdirSync(folder, { recursive: true });
  writeFileSync(
    join(folder, 'index.html'),
    withHead(shellHtml, {
      title: fullTitle(SITE_NAME, page.title),
      description: page.description,
      url: new URL(page.path, `${environment.siteUrl}/`).href,
      robots: 'index, follow',
      image: page.image,
    }),
  );
}

writeFileSync(
  join(out, '.htaccess'),
  `# Generated by scripts/build-afrihost.mjs. Upload with the rest of this folder.
DirectoryIndex index.html
Options -Indexes
# /login is a folder holding a prerendered page: serve it without redirecting to /login/.
DirectorySlash Off

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase /

  # One address for the site: https://toniribeiro.co.za
  RewriteCond %{HTTPS} !=on
  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]
  RewriteCond %{HTTP_HOST} ^www\\.(.+)$ [NC]
  RewriteRule ^ https://%1%{REQUEST_URI} [L,R=301]

  # The home page is switched off: / opens the lift club. Temporary (302), so that browsers
  # and search engines don't hold on to it once the home page returns.
  RewriteRule ^(index\\.html)?$ /${LIFT_CLUB_PAGE.path} [L,R=302]

  # Pages with their own HTML: /login -> /login/index.html, /lift-club -> /lift-club/index.html
  RewriteCond %{REQUEST_FILENAME} -d
  RewriteCond %{REQUEST_FILENAME}/index.html -f
  RewriteRule ^(.+?)/?$ $1/index.html [L]

  # Everything else that is not a real file is an app route (for example /reset-password).
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteRule ^ /${shell} [L]
</IfModule>

<IfModule mod_headers.c>
  # Pages must always be fresh; the fingerprinted scripts and styles never change.
  <FilesMatch "\\.html$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
  <FilesMatch "-[A-Za-z0-9_-]{8}\\.(js|css)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.(mp4|webm|webp)$">
    Header set Cache-Control "public, max-age=86400"
  </FilesMatch>
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set Cross-Origin-Opener-Policy "same-origin-allow-popups"
  Header always set X-Content-Type-Options "nosniff"
</IfModule>
`,
);

console.log(`\nReady: upload the CONTENTS of ${out} to public_html (include .htaccess).`);
